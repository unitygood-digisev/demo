def _write(name: str, header: list[str], rows: list[list]) -> Path:
    wb = Workbook()
    ws = wb.active
    ws.title = "資料"
    ws.append(header)
    for r in rows:
        ws.append(r)
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            if isinstance(cell.value, dt.date):
                cell.number_format = "yyyy-mm-dd"
    note = wb.create_sheet("說明")
    note.append([NOTE])
    wb.properties.title = "假資料"
    wb.properties.creator = "unity-mgmt-suite"
    wb.properties.created = dt.datetime(2000, 1, 1)
    wb.properties.modified = dt.datetime(2000, 1, 1)
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / name
    wb.save(path)
    return path


